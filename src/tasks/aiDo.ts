/**
 * «Сделать с ИИ»: ИИ выполняет задачу за человека — готовит презентацию, текст, письмо, план.
 * Модуль чистый — тесты гоняют его в Node.
 */
import type { TaskItem } from './model';

/** Границы слов в регулярных выражениях JS не работают для кириллицы — соседние буквы проверяем явно */
const L = 'а-яёәіңғүұқөһ';
const word = (w: string) => `(?<![${L}])${w}(?![${L}])`;
const DOABLE_RE = new RegExp(
  [
    'презентац', 'слайд', 'доклад', 'отч[её]т', 'эссе', 'сочинени', 'реферат', 'курсов', 'диплом', 'стать[юяи]', word('пост'), 'посты', 'письм', 'e-?mail', 'имейл',
    'резюме', 'сопроводит', 'текст', 'перев[её]д', 'переве', 'конспект', 'сценари', word('реч[ьи]'), word('тост'), 'поздравлени', 'описани', 'коммерческ',
    'предложени', 'договор', 'бизнес-?план', word('план'), 'стратеги', 'анализ', 'исследова', 'таблиц', 'расч[её]т', 'посчита', 'бюджет', 'смет', word('идеи'),
    'придума', 'написа', 'подготов', 'состав(?:ит|ь)', 'сочини', 'разработа', 'оформи', 'ответить на', 'отзыв', 'инструкци', 'чек-?лист', word('тест'),
    'вопросы к', 'домашк', 'д/з', word('код'), 'скрипт', 'лендинг', 'слоган', 'название для', 'баяндам', word('хат'), 'мәтін', 'аудар',
    String.raw`\b(?:presentation|slides?|report|essay|letter|e-?mail|draft|write|prepare|translate|summary|proposal|plan|post|speech|script)\b`,
  ].join('|'),
  'i',
);

/** Задачи, которые ИИ реально может сделать (что-то написать, придумать, посчитать), а не «купить хлеб» */
export function aiCanDo(task: Pick<TaskItem, 'title' | 'notes'>): boolean {
  return DOABLE_RE.test(task.title) || (!!task.notes && DOABLE_RE.test(task.notes.slice(0, 400)));
}

/** Срок близко: сегодня, завтра или уже прошёл, а задача не сделана */
export function dueSoon(task: TaskItem, today: string, tomorrow: string): boolean {
  return !task.done && !task.wontDo && !task.deleted && !!task.date && task.date <= tomorrow && task.date >= addDays(today, -7);
}

export function addDays(ymd: string, n: number): string {
  const [y, m, d] = ymd.split('-').map(Number);
  const x = new Date(Date.UTC(y, m - 1, d + n));
  return x.toISOString().slice(0, 10);
}

/** Задание для ИИ: что сделать, срок, описание и подзадачи */
export function taskBrief(task: Pick<TaskItem, 'title' | 'notes' | 'date' | 'time' | 'checklist'>, wish = ''): string {
  const parts = [`Выполни за меня задачу: «${task.title.trim()}».`];
  if (task.date) parts.push(`Срок: ${task.date}${task.time ? ' ' + task.time : ''}.`);
  // прошлые результаты ИИ в описании не повторяем — только то, что написал человек
  const notes = (task.notes ?? '').split(/\n*— Результат ИИ/)[0].trim();
  if (notes) parts.push(`Описание и детали:\n${notes.slice(0, 3000)}`);
  const steps = (task.checklist ?? []).filter((c) => c.text.trim());
  if (steps.length) parts.push(`Шаги, которые я наметил:\n${steps.map((c) => `- ${c.done ? '[x] ' : ''}${c.text.trim()}`).join('\n')}`);
  if (wish.trim()) parts.push(`Пожелания: ${wish.trim()}`);
  parts.push(
    'Сделай сразу готовый результат, который можно использовать, а не советы, как его сделать. Если это презентация — дай слайды: заголовок, 3–5 пунктов и что сказать на каждом слайде. Если нужна информация, которой нет, — сделай разумные допущения и отметь их в конце.',
  );
  return parts.join('\n\n');
}

/** Встроенный ИИ: ответ — готовый документ в Markdown, первая строка — заголовок */
