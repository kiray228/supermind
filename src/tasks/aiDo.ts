/** Заголовок результата: первая строка «# …», иначе — название задачи */
export function resultTitle(md: string, fallback: string): string {
  const m = /^\s*#\s+(.+)$/m.exec(md);
  return (m ? m[1] : fallback).replace(/[*_`]/g, '').trim().slice(0, 120) || fallback;
}

/** Текст без первой строки-заголовка (заголовок уходит в название заметки) */
export function resultBody(md: string): string {
  return md.replace(/^\s*#\s+.+\n?/, '').trim();
}

